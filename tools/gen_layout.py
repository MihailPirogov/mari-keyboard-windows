#!/usr/bin/env python3
"""Generate kbdmari.c / kbdmari.rc / kbdmari.def / kbdmari.klc from layout JSON."""
import json, sys, os, unicodedata
SRC = os.path.join(os.path.dirname(__file__), '..', 'src')
L = json.load(open(os.path.join(SRC, 'layout_original.json'), encoding='utf-8'))
VER = (3, 1, 0, 0)
NAME = 'kbdmari'
AUTHOR = 'Михаил Пирогов'
LAYOUT_NAME = 'Марийская'
LANG_NAME = 'Марийский'
LANG_TAG = 'mhr-Cyrl'
WCH_NONE, WCH_DEAD, WCH_LGTR = 0xF000, 0xF001, 0xF002
CAPLOK, SGCAPS, CAPLOKALTGR, KANALOK, GRPSELTAP = 1, 2, 4, 8, 0x80

# --- Improvement over the 2013 DLL: make Caps Lock also apply to AltGr letters
# (in mari1.dll ӓ ӧ ӱ ӹ ҥ etc. ignored Caps Lock on some keys).
fixed = []
for t in L['tables']:
    if t['nmod'] == 5:
        for row in t['rows']:
            vk, attr, w = row
            if attr & CAPLOK and w[3] not in (WCH_NONE,) and w[4] not in (WCH_NONE,):
                a, b = chr(w[3]), chr(w[4])
                if a != b and a.upper() == b and not (attr & CAPLOKALTGR):
                    row[1] = attr | CAPLOKALTGR; fixed.append(a)
print('CAPLOKALTGR added for:', ''.join(fixed))

def wlit(w):
    return {WCH_NONE: 'WCH_NONE', WCH_DEAD: 'WCH_DEAD', WCH_LGTR: 'WCH_LGTR'}.get(w, '0x%04x' % w)
def cstr(s):
    return 'L"' + ''.join(c if (32 <= ord(c) < 127 and c not in '"\\') else '\\x%04x' % ord(c) for c in s) + '"'

c = []
c.append('''/*
 * kbdmari.c - Марийская раскладка клавиатуры (Mari keyboard layout)
 * Generated by tools/gen_layout.py from the layout of mari1.dll (Windows 7 version).
 * Build: clang --target=<arch>-pc-windows-msvc, see build.sh.
 * Define KBD_WOW64 for the 32-bit SysWOW64 build (64-bit table pointers, as with
 * MSKLC's BUILD_WOW6432 / KBD_LONG_POINTER __ptr64).
 */
typedef unsigned char BYTE;
typedef unsigned short WORD;
typedef unsigned short USHORT;
typedef unsigned int DWORD;
typedef unsigned short WCHAR; /* == wchar_t on Windows */

#ifdef KBD_WOW64
#define KPTR(T) union { T p; unsigned long long _p64; }
#define PV(x) { (x) }
#else
#define KPTR(T) T
#define PV(x) (x)
#endif

#define WCH_NONE 0xF000
#define WCH_DEAD 0xF001
#define WCH_LGTR 0xF002
#define KBDSHIFT 1
#define KBDCTRL  2
#define KBDALT   4
#define SHFT_INVALID 0x0F
#define CAPLOK      0x01
#define SGCAPS      0x02
#define CAPLOKALTGR 0x04
#define KLLF_ALTGR  0x0001
#define KBD_VERSION 1
#define KBDEXT      0x0100
#define KBDMULTIVK  0x0200
#define KBDSPECIAL  0x0400
#define KBDNUMPAD   0x0800

typedef struct { BYTE Vk; BYTE ModBits; } VK_TO_BIT;
typedef struct { KPTR(const VK_TO_BIT *) pVkToBit; WORD wMaxModBits; BYTE ModNumber[%d]; } MODIFIERS;
typedef struct { KPTR(const void *) pVkToWchars; BYTE nModifications; BYTE cbSize; } VK_TO_WCHAR_TABLE;
typedef struct { BYTE vsc; KPTR(const WCHAR *) pwsz; } VSC_LPWSTR;
typedef struct { BYTE Vsc; USHORT Vk; } VSC_VK;
typedef struct {
    KPTR(const MODIFIERS *) pCharModifiers;
    KPTR(const VK_TO_WCHAR_TABLE *) pVkToWcharTable;
    KPTR(const void *) pDeadKey;
    KPTR(const VSC_LPWSTR *) pKeyNames;
    KPTR(const VSC_LPWSTR *) pKeyNamesExt;
    KPTR(const void *) pKeyNamesDead;
    KPTR(const USHORT *) pusVSCtoVK;
    BYTE bMaxVSCtoVK;
    KPTR(const VSC_VK *) pVSCtoVK_E0;
    KPTR(const VSC_VK *) pVSCtoVK_E1;
    DWORD fLocaleFlags;
    BYTE nLgMax;
    BYTE cbLgEntry;
    KPTR(const void *) pLigature;
    DWORD dwType;
    DWORD dwSubType;
} KBDTABLES;

_Static_assert(sizeof(VK_TO_WCHAR_TABLE) == sizeof(void*) * 2 || sizeof(VK_TO_WCHAR_TABLE) == 16, "layout");
''' % len(L['modnumber']))
# VSC -> VK
v = L['vsc_to_vk']
c.append('static const USHORT ausVK[] = {\n' + ',\n'.join('    ' + ', '.join('0x%04x' % x for x in v[i:i+8]) for i in range(0, len(v), 8)) + '\n};\n')
for nm, arr in (('E0', L['e0']), ('E1', L['e1'])):
    c.append('static const VSC_VK aE%sVscToVk[] = {\n' % nm[1] + ''.join('    { 0x%02x, 0x%04x },\n' % (s, k) for s, k in arr) + '    { 0, 0 }\n};\n')
c.append('static const VK_TO_BIT aVkToBits[] = {\n' + ''.join('    { 0x%02x, %d },\n' % (a, b) for a, b in L['modbits']) + '    { 0, 0 }\n};\n')
c.append('static const MODIFIERS CharModifiers = {\n    PV(aVkToBits), %d,\n    { %s }\n};\n' % (len(L['modnumber']) - 1, ', '.join(str(x) for x in L['modnumber'])))
for t in L['tables']:
    n = t['nmod']
    c.append('typedef struct { BYTE VirtualKey; BYTE Attributes; WCHAR wch[%d]; } VK_TO_WCHARS%d;\n' % (n, n))
    c.append('static const VK_TO_WCHARS%d aVkToWch%d[] = {\n' % (n, n))
    for vk, attr, w in t['rows']:
        cm = ' '.join(chr(x) if 0x20 < x < 0xF000 else '.' for x in w)
        c.append('    { 0x%02x, 0x%02x, { %s } }, /* %s */\n' % (vk, attr, ', '.join(wlit(x) for x in w), cm))
    c.append('    { 0, 0, { %s } }\n};\n' % ', '.join(['0'] * n))
c.append('static const VK_TO_WCHAR_TABLE aVkToWcharTable[] = {\n' +
         ''.join('    { PV(aVkToWch%d), %d, sizeof(aVkToWch%d[0]) },\n' % (t['nmod'], t['nmod'], t['nmod']) for t in L['tables']) +
         '    { PV(0), 0, 0 }\n};\n')
for nm, key in (('aKeyNames', 'keynames'), ('aKeyNamesExt', 'keynames_ext')):
    c.append('static const VSC_LPWSTR %s[] = {\n' % nm + ''.join('    { 0x%02x, PV(%s) },\n' % (s, cstr(x)) for s, x in L[key]) + '    { 0, PV(0) }\n};\n')
c.append('''static const KBDTABLES KbdTables = {
    PV(&CharModifiers),
    PV(aVkToWcharTable),
    PV(0),
    PV(aKeyNames),
    PV(aKeyNamesExt),
    PV(0),
    PV(ausVK),
    sizeof(ausVK) / sizeof(ausVK[0]),
    PV(aE0VscToVk),
    PV(aE1VscToVk),
    (KLLF_ALTGR) | ((DWORD)KBD_VERSION << 16),
    0, 0, PV(0),
    4, 0
};

/* The only export, ordinal 1 (see kbdmari.def). */
const KBDTABLES *KbdLayerDescriptor(void)
{
    return &KbdTables;
}
''')
open(os.path.join(SRC, NAME + '.c'), 'w', encoding='utf-8').write(''.join(c))
open(os.path.join(SRC, NAME + '.def'), 'w').write('LIBRARY %s\nEXPORTS\n    KbdLayerDescriptor @1\n' % NAME)

vs = '%d.%d.%d.%d' % VER
rc = f'''#pragma code_page(65001)
// kbdmari.rc — ресурсы раскладки
LANGUAGE 0, 0

1 VERSIONINFO
 FILEVERSION {VER[0]},{VER[1]},{VER[2]},{VER[3]}
 PRODUCTVERSION {VER[0]},{VER[1]},{VER[2]},{VER[3]}
 FILEFLAGSMASK 0x3fL
 FILEFLAGS 0x0L
 FILEOS 0x40004L
 FILETYPE 0x2L
 FILESUBTYPE 0x0L
BEGIN
    BLOCK "StringFileInfo"
    BEGIN
        BLOCK "041904b0"
        BEGIN
            VALUE "Comments", "Файл из проекта pirogovlab.ru — https://pirogovlab.ru"
            VALUE "CompanyName", "Пирогов Михаил"
            VALUE "URL", "https://pirogovlab.ru"
            VALUE "FileDescription", "Марийская раскладка клавиатуры (Mari keyboard layout)"
            VALUE "FileVersion", "{vs}"
            VALUE "InternalName", "{NAME} ({VER[0]}.{VER[1]})"
            VALUE "LegalCopyright", "© {AUTHOR}"
            VALUE "OriginalFilename", "{NAME}.dll"
            VALUE "ProductName", "Марийская раскладка клавиатуры"
            VALUE "ProductVersion", "{vs}"
        END
    END
    BLOCK "VarFileInfo"
    BEGIN
        VALUE "Translation", 0x419, 1200
    END
END

STRINGTABLE
BEGIN
    1000 "{LAYOUT_NAME}"
    1100 "{LANG_NAME}"
    1200 "{LANG_TAG}"
END
'''
open(os.path.join(SRC, NAME + '.rc'), 'w', encoding='utf-8').write(rc)

# ---------- MSKLC .klc ----------
VKN = {0x20:'SPACE',0xBA:'OEM_1',0xBB:'OEM_PLUS',0xBC:'OEM_COMMA',0xBD:'OEM_MINUS',0xBE:'OEM_PERIOD',0xBF:'OEM_2',0xC0:'OEM_3',
       0xDB:'OEM_4',0xDC:'OEM_5',0xDD:'OEM_6',0xDE:'OEM_7',0xE2:'OEM_102',0x6E:'DECIMAL'}
def vkname(vk): return VKN.get(vk, chr(vk))
sc_of = {}
for sc, vk in enumerate(L['vsc_to_vk']):
    vk &= 0xFF
    if vk not in sc_of: sc_of[vk] = sc
sc_of[0x6E] = 0x53
def kch(w):
    if w == WCH_NONE: return '-1'
    if 0x21 <= w < 0x7F and chr(w) not in '/;@': return chr(w)
    return '%04x' % w
k = []
k.append(f'KBD\t{NAME}\t"{LAYOUT_NAME}"\r\n\r\nCOPYRIGHT\t"(c) {AUTHOR}"\r\n\r\nCOMPANY\t"{AUTHOR}"\r\n\r\n'
         'LOCALENAME\t"ru-RU"\r\n\r\nLOCALEID\t"00000419"\r\n\r\nVERSION\t3.1\r\n\r\n'
         'SHIFTSTATE\r\n\r\n0\t//Column 4\r\n1\t//Column 5 : Shft\r\n2\t//Column 6 :       Ctrl\r\n6\t//Column 7 :       Ctrl Alt\r\n7\t//Column 8 : Shft  Ctrl Alt\r\n\r\n'
         'LAYOUT\t\t;an extra \'@\' at the end is a dead key\r\n\r\n//SC\tVK_\t\tCap\t0\t1\t2\t6\t7\r\n//--\t----\t\t----\t----\t----\t----\t----\t----\r\n\r\n')
rows = [r for t in L['tables'] if t['nmod'] == 5 for r in t['rows']]
rows.sort(key=lambda r: sc_of[r[0]])
for vk, attr, w in rows:
    cap = {0: '0', 1: '1', 4: '4', 5: '5', 2: 'SGCap'}[attr]
    desc = ', '.join(unicodedata.name(chr(x), '%04x' % x) for x in w if x != WCH_NONE and x >= 0x20)
    k.append('%02x\t%s\t\t%s\t%s\t// %s\r\n' % (sc_of[vk], vkname(vk), cap, '\t'.join(kch(x) for x in w), desc))
k.append('53\tDECIMAL\t\t0\t002c\t002c\t-1\t-1\t-1\t// COMMA, COMMA\r\n' if False else '')
k.append('\r\n\r\nKEYNAME\r\n\r\n' + ''.join('%02x\t%s\r\n' % (s, ('"%s"' % n) if ' ' in n else n) for s, n in L['keynames']))
k.append('\r\nKEYNAME_EXT\r\n\r\n' + ''.join('%02x\t%s\r\n' % (s, ('"%s"' % n) if ' ' in n else n) for s, n in L['keynames_ext']))
k.append(f'\r\nDESCRIPTIONS\r\n\r\n0419\t{LAYOUT_NAME}\r\n\r\nLANGUAGENAMES\r\n\r\n0419\tРусский (Россия)\r\n\r\nENDKBD\r\n')
open(os.path.join(SRC, NAME + '.klc'), 'wb').write(b'\xff\xfe' + ''.join(k).encode('utf-16le'))
print('generated')
